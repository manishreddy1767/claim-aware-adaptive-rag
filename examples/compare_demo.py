"""Demo: traditional RAG versus Claim-Aware Adaptive RAG on aurora_station_manual.pdf.

Traditional RAG = fixed hybrid top-5 retrieval + a local LLM with the common
"use the context, say you don't know" prompt, and no checking of the answer.
Claim-Aware RAG = the quoted answer (rag.ask) and the AI answer (rag.ask_with_llm,
same LLM, every claim verified). Writes examples/aurora_demo_results.md.

    python -m examples.compare_demo [--model llama3.2:3b]
"""

from __future__ import annotations

import argparse
from pathlib import Path

from carag.llm import LLMGenerator, OllamaClient, choose, discover
from carag.pipeline import ClaimAwareRAG

HERE = Path(__file__).resolve().parent

TRADITIONAL_PROMPT = ("Use the following pieces of context to answer the question at the end. "
                      "If you don't know the answer, just say that you don't know, don't try to make up an answer.")

# (question or text to check, what a correct answer must do, which feature it tests)
QUESTIONS = [
    ("What is the maximum number of residents the station can accommodate?",
     "Report both 24 (section 2) and 30 (2026 update), not one of them silently.", "conflicting sources"),
    ("Since boat requests are approved automatically, how early must I submit one?",
     "Correct the premise (approval is not automatic) and give the 48-hour rule.", "false premise"),
    ("Are water samples sent to the central laboratory every week?",
     "No: every 2 weeks.", "time-quantity check"),
    ("When does the winter shutdown start and end?",
     "Say the manual does not specify the dates (it only describes the shutdown).", "not specified"),
    ("How much does family accommodation cost per night?",
     "Say the manual does not cover it.", "not specified"),
    ("What is the station's Wi-Fi password policy?",
     "Say the documents do not contain this.", "absent topic"),
    ("Can a researcher walk alone on the lake ice when it is 20 centimetres thick?",
     "No: ice travel is never allowed alone (thickness is enough).", "condition reasoning"),
    ("What is the procedure for requesting a research boat, including the deadline and approvals?",
     "FieldDesk, 48 hours, crew/site/return time, duty officer approval (not automatic), "
     "director approval beyond the outer buoy line.", "multi-part completeness"),
    ("Who funds the Aurora Lake Research Station?",
     "Say funding is not stated (it is operated by the Northern Lakes Institute).", "absent detail"),
    ("Can any researcher borrow a drone for a week?",
     "No: drones up to 3 days, certified pilots only.", "false premise"),
]

CHECK_TEXT = ("Visiting researchers can stay at Aurora Lake for up to 30 days. Boat requests must be made "
              "48 hours in advance. Any researcher may fly the station's drones. Fish surveys happen every month.")


def traditional(rag: ClaimAwareRAG, generator: LLMGenerator, question: str) -> str:
    evidence = rag.retriever.rank(question, 5, "hybrid")
    context = "\n".join(e.unit.text for e in evidence)
    return generator.client.chat(generator.model, TRADITIONAL_PROMPT,
                                 f"Context:\n{context}\n\nQuestion: {question}\nHelpful answer:")


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--model", default="auto")
    args = parser.parse_args(argv)
    picked = choose(discover(), args.model)
    if picked is None:
        raise SystemExit("No local LLM found (start Ollama or another local server).")
    server, model = picked
    from carag.llm import client_for
    generator = LLMGenerator(model, client_for(server.name, server.url, server.kind))

    rag = ClaimAwareRAG()
    rag.add_source(str(HERE / "aurora_station_manual.pdf"))
    out = [f"# Traditional RAG vs Claim-Aware Adaptive RAG: Aurora station manual\n",
           f"Generated by `python -m examples.compare_demo` with `{model}` ({server.name}). "
           "Traditional RAG: fixed hybrid top-5 + the LLM with a standard RAG prompt, no checks. "
           "Claim-Aware RAG: quoted answer and AI answer (same LLM, every claim verified).\n"]
    for n, (question, expected, feature) in enumerate(QUESTIONS, start=1):
        trad = traditional(rag, generator, question).strip()
        quoted = rag.ask(question)
        ai = rag.ask_with_llm(question, generator)
        ai_text, ai_outcome = ai.text, ai.outcome
        if ai.abstained and not quoted.abstained:
            # As in the application: an unverifiable AI draft falls back to the quoted answer.
            ai_text, ai_outcome = f"(AI draft not verifiable; quoted answer shown) {quoted.answer}", quoted.outcome
        out += [f"## {n}. {question}\n", f"*Tests:* {feature}. *A correct answer:* {expected}\n",
                f"**Traditional RAG:**\n\n> {trad.replace(chr(10), chr(10) + '> ')}\n",
                f"**Claim-Aware RAG, quoted** (`{quoted.outcome}`):\n\n> {quoted.answer.replace(chr(10), chr(10) + '> ')}\n",
                f"**Claim-Aware RAG, AI answer** (`{ai_outcome}`):\n\n> {ai_text.replace(chr(10), chr(10) + '> ')}\n"]
        print(f"done {n}/{len(QUESTIONS)}", flush=True)
    check = rag.check_answer(CHECK_TEXT)
    out += ["## Checking a chatbot's answer\n", f"Pasted text:\n\n> {CHECK_TEXT}\n",
            f"**Claim-Aware RAG, Check a text:**\n\n> {check.revised.text.replace(chr(10), chr(10) + '> ')}\n",
            "Traditional RAG has no equivalent: it cannot check a given text against the documents.\n"]
    (HERE / "aurora_demo_results.md").write_text("\n".join(out), encoding="utf-8")
    print("Wrote", HERE / "aurora_demo_results.md")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
